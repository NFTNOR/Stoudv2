/**
 * STOUD — Password setup
 * Run: node setup-password.js
 * Generates .env with a secure SESSION_SECRET and hashed ADMIN_PASSWORD_HASH
 */
const bcrypt = require('bcrypt');
const crypto = require('crypto');
const fs     = require('fs');
const readline = require('readline');

const rl = readline.createInterface({ input: process.stdin, output: process.stdout });

console.log('\n── STOUD Server Setup ──\n');

rl.question('Enter admin password: ', async (password) => {
  if (!password || password.length < 8) {
    console.error('Password must be at least 8 characters.');
    rl.close(); process.exit(1);
  }

  const hash   = await bcrypt.hash(password, 12);  // 12 rounds = ~300ms, very secure
  const secret = crypto.randomBytes(64).toString('hex');

  const env = `# STOUD Server — Environment Variables
# Keep this file SECRET — never commit to git

NODE_ENV=production
PORT=3000

# Change if deploying to a different path
# SESSION_SECRET — random 64-byte hex string
SESSION_SECRET=${secret}

# Bcrypt hash of admin password (generated by setup-password.js)
ADMIN_PASSWORD_HASH=${hash}
`;

  fs.writeFileSync('.env', env, { mode: 0o600 }); // owner read/write only

  console.log('\n✓ .env file created');
  console.log('✓ Password hash generated (bcrypt, 12 rounds)');
  console.log('✓ Session secret generated (64-byte random)');
  console.log('\n  Keep .env safe — never share or commit it.');
  console.log('  Start server: npm start\n');

  rl.close();
});
